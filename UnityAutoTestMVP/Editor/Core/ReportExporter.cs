using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;

namespace UnityAutoTestMVP
{
    public enum ReportFormat
    {
        Json = 0,
        Markdown = 1
    }

    public sealed class ReportExportResult
    {
        public string JsonPath = string.Empty;
        public string MarkdownPath = string.Empty;
        public string Error = string.Empty;

        public bool Success
        {
            get { return string.IsNullOrEmpty(Error); }
        }
    }

    /// <summary>
    /// JSON / Markdown 报告落盘。默认目录：&lt;Project&gt;/Library/UnityAutoTestMVP/Reports。
    /// 文件名包含时间戳与任务 ID，不会覆盖历史报告。
    /// 本类不依赖 UnityEngine，便于独立编译测试。
    /// </summary>
    public static class ReportExporter
    {
        private static readonly Encoding Utf8NoBom = new UTF8Encoding(false);

        public static string GetReportsDirectory(string projectRoot)
        {
            if (string.IsNullOrEmpty(projectRoot))
            {
                throw new ArgumentException("项目根目录为空，无法确定报告目录。", "projectRoot");
            }

            return Path.Combine(projectRoot, "Library", "UnityAutoTestMVP", "Reports");
        }

        public static string BuildFileName(TestReport report, ReportFormat format)
        {
            if (report == null)
            {
                throw new ArgumentNullException("report");
            }

            string timestamp = report.StartedAtUtc.ToLocalTime().ToString("yyyyMMdd_HHmmss_fff", CultureInfo.InvariantCulture);
            string type = report.TestType == TestType.SmokeTest ? "SmokeTest" : "ProjectScan";
            string taskSuffix = string.IsNullOrEmpty(report.TaskId)
                ? "notask"
                : report.TaskId.Substring(0, Math.Min(8, report.TaskId.Length));
            string extension = format == ReportFormat.Markdown ? ".md" : ".json";
            return timestamp + "_" + type + "_" + taskSuffix + extension;
        }

        public static string BuildJson(TestReport report)
        {
            return AutoTestJson.SerializeReport(report);
        }

        public static string BuildMarkdown(TestReport report)
        {
            if (report == null)
            {
                throw new ArgumentNullException("report");
            }

            StringBuilder sb = new StringBuilder(8192);
            sb.AppendLine("# Unity Auto Test MVP 检测报告");
            sb.AppendLine();

            if (report.TestType == TestType.SmokeTest)
            {
                sb.AppendLine("> 这是**基础冒烟测试**报告：只验证当前场景能进入 Play Mode 并在设定时长内没有捕获目标错误日志，");
                sb.AppendLine("> 不代表游戏玩法、UI、关卡或业务逻辑已经全部正确。");
                sb.AppendLine();
            }

            AppendBasicInfo(sb, report);
            AppendSummary(sb, report);
            AppendIssues(sb, report);
            AppendNotes(sb, report);

            sb.AppendLine();
            sb.AppendLine("---");
            sb.AppendLine();
            sb.AppendLine("*Generated by " + AutoTestConstants.ToolName + " v" + EscapeInline(report.ToolVersion) + "*");
            return sb.ToString();
        }

        private static void AppendBasicInfo(StringBuilder sb, TestReport report)
        {
            sb.AppendLine("## 基本信息");
            sb.AppendLine();
            sb.AppendLine("| 字段 | 内容 |");
            sb.AppendLine("| --- | --- |");
            AppendTableRow(sb, "任务 ID", report.TaskId);
            AppendTableRow(sb, "测试类型", TestTypeLabel(report.TestType));
            AppendTableRow(sb, "总体状态", "**" + StatusLabel(report.OverallStatus) + "**");
            AppendTableRow(sb, "开始时间", FormatLocalTime(report.StartedAtUtc));
            AppendTableRow(sb, "结束时间", FormatLocalTime(report.FinishedAtUtc));
            AppendTableRow(sb, "耗时", report.DurationSeconds.ToString("0.00", CultureInfo.InvariantCulture) + " 秒");
            AppendTableRow(sb, "Unity 版本", report.UnityVersion);
            AppendTableRow(sb, "项目名称", report.ProjectName);
            AppendTableRow(sb, "项目路径", report.ProjectPath);
            if (!string.IsNullOrEmpty(report.ScenePath))
            {
                AppendTableRow(sb, "目标场景", report.ScenePath);
            }

            sb.AppendLine();
        }

        private static void AppendSummary(StringBuilder sb, TestReport report)
        {
            TestSummary summary = report.Summary ?? new TestSummary();
            sb.AppendLine("## 统计");
            sb.AppendLine();
            sb.AppendLine("| 检查项总数 | 通过 | 失败 | 警告 | 未执行 | 已取消 |");
            sb.AppendLine("| ---: | ---: | ---: | ---: | ---: | ---: |");
            sb.AppendLine("| " + summary.Total.ToString(CultureInfo.InvariantCulture) +
                          " | " + summary.Passed.ToString(CultureInfo.InvariantCulture) +
                          " | " + summary.Failed.ToString(CultureInfo.InvariantCulture) +
                          " | " + summary.Warning.ToString(CultureInfo.InvariantCulture) +
                          " | " + summary.NotRun.ToString(CultureInfo.InvariantCulture) +
                          " | " + summary.Cancelled.ToString(CultureInfo.InvariantCulture) + " |");
            sb.AppendLine();
        }

        private static void AppendIssues(StringBuilder sb, TestReport report)
        {
            sb.AppendLine("## 检查结果");
            sb.AppendLine();

            if (report.Issues == null || report.Issues.Count == 0)
            {
                sb.AppendLine("本次没有记录任何检查项。");
                sb.AppendLine();
                return;
            }

            for (int i = 0; i < report.Issues.Count; i++)
            {
                TestIssue issue = report.Issues[i];
                if (issue == null)
                {
                    continue;
                }

                string heading = string.IsNullOrEmpty(issue.Title) ? "未命名检查项" : issue.Title;
                sb.AppendLine("### " + (i + 1).ToString(CultureInfo.InvariantCulture) + ". [" + StatusLabel(issue.Status) + "] " + EscapeHeading(heading));
                sb.AppendLine();
                sb.AppendLine("- 检查项 ID：" + EscapeInline(issue.Id));
                sb.AppendLine("- 类别：" + CategoryLabel(issue.Category));
                sb.AppendLine("- 严重等级：" + SeverityLabel(issue.Severity));
                if (!string.IsNullOrEmpty(issue.ScenePath))
                {
                    sb.AppendLine("- 场景：" + EscapeInline(issue.ScenePath));
                }

                if (!string.IsNullOrEmpty(issue.GameObjectPath))
                {
                    sb.AppendLine("- GameObject：" + EscapeInline(issue.GameObjectPath));
                }

                if (!string.IsNullOrEmpty(issue.Description))
                {
                    sb.AppendLine("- 说明：" + EscapeMultiline(issue.Description));
                }

                if (!string.IsNullOrEmpty(issue.Suggestion))
                {
                    sb.AppendLine("- 修复建议：" + EscapeMultiline(issue.Suggestion));
                }

                if (!string.IsNullOrEmpty(issue.Message))
                {
                    sb.AppendLine();
                    sb.AppendLine("错误消息：");
                    sb.AppendLine();
                    sb.AppendLine("````text");
                    sb.AppendLine(Truncate(issue.Message, AutoTestConstants.MaxStackCharacters));
                    sb.AppendLine("````");
                }

                if (!string.IsNullOrEmpty(issue.StackTrace))
                {
                    sb.AppendLine();
                    sb.AppendLine("堆栈信息：");
                    sb.AppendLine();
                    sb.AppendLine("````text");
                    sb.AppendLine(Truncate(issue.StackTrace, AutoTestConstants.MaxStackCharacters));
                    sb.AppendLine("````");
                }

                sb.AppendLine();
            }
        }

        private static void AppendNotes(StringBuilder sb, TestReport report)
        {
            sb.AppendLine("## 说明与限制");
            sb.AppendLine();
            if (report.Notes == null || report.Notes.Count == 0)
            {
                sb.AppendLine("- 无附加说明。");
            }
            else
            {
                for (int i = 0; i < report.Notes.Count; i++)
                {
                    string note = report.Notes[i];
                    if (!string.IsNullOrEmpty(note))
                    {
                        sb.AppendLine("- " + EscapeMultiline(note));
                    }
                }
            }

            sb.AppendLine();
            sb.AppendLine("- 本工具不会自动修复、删除或覆盖任何场景、Prefab、脚本或项目设置。");
            sb.AppendLine("- 本工具不上传任何项目代码、日志或场景内容到外部服务。");
        }

        private static void AppendTableRow(StringBuilder sb, string label, string value)
        {
            sb.AppendLine("| " + EscapeCell(label) + " | " + EscapeCell(value) + " |");
        }

        private static string FormatLocalTime(DateTime utc)
        {
            if (utc == default(DateTime))
            {
                return "（未知）";
            }

            return utc.ToLocalTime().ToString("yyyy-MM-dd HH:mm:ss zzz", CultureInfo.InvariantCulture);
        }

        private static string TestTypeLabel(TestType type)
        {
            switch (type)
            {
                case TestType.SmokeTest:
                    return "运行时冒烟测试 (SmokeTest)";
                default:
                    return "项目静态扫描 (ProjectScan)";
            }
        }

        private static string StatusLabel(TestStatus status)
        {
            switch (status)
            {
                case TestStatus.Passed:
                    return "通过 (Passed)";
                case TestStatus.Failed:
                    return "失败 (Failed)";
                case TestStatus.Warning:
                    return "警告 (Warning)";
                case TestStatus.Cancelled:
                    return "已取消 (Cancelled)";
                default:
                    return "未执行 (NotRun)";
            }
        }

        private static string SeverityLabel(IssueSeverity severity)
        {
            switch (severity)
            {
                case IssueSeverity.Critical:
                    return "严重 (Critical)";
                case IssueSeverity.Error:
                    return "错误 (Error)";
                case IssueSeverity.Warning:
                    return "警告 (Warning)";
                default:
                    return "信息 (Info)";
            }
        }

        private static string CategoryLabel(IssueCategory category)
        {
            switch (category)
            {
                case IssueCategory.SceneAsset:
                    return "场景资源 (SceneAsset)";
                case IssueCategory.SceneLoad:
                    return "场景加载 (SceneLoad)";
                case IssueCategory.MissingScript:
                    return "脚本缺失 (MissingScript)";
                case IssueCategory.SceneScan:
                    return "场景扫描 (SceneScan)";
                case IssueCategory.RuntimeError:
                    return "运行时错误 (RuntimeError)";
                case IssueCategory.RuntimeWarning:
                    return "运行时警告 (RuntimeWarning)";
                case IssueCategory.CompilationError:
                    return "编译错误 (CompilationError)";
                case IssueCategory.CompilationWarning:
                    return "编译警告 (CompilationWarning)";
                case IssueCategory.CompilationState:
                    return "编译状态 (CompilationState)";
                case IssueCategory.TestInfrastructure:
                    return "测试环境 (TestInfrastructure)";
                default:
                    return "项目扫描 (ProjectScan)";
            }
        }

        private static string EscapeInline(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return "（无）";
            }

            string safe = value.Replace("\r", " ").Replace("\n", " ").Replace("`", "'");
            return "`" + safe + "`";
        }

        private static string EscapeCell(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return "（无）";
            }

            return value.Replace("\\", "\\\\").Replace("|", "\\|").Replace("\r", "").Replace("\n", "<br>");
        }

        private static string EscapeHeading(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return string.Empty;
            }

            return value.Replace("\r", " ").Replace("\n", " ").Replace("#", "\\#");
        }

        private static string EscapeMultiline(string value)
        {
            if (string.IsNullOrEmpty(value))
            {
                return string.Empty;
            }

            return value.Replace("\r\n", "\n").Replace("\r", "\n").Replace("\n", "<br>");
        }

        private static string Truncate(string value, int maxLength)
        {
            if (string.IsNullOrEmpty(value) || value.Length <= maxLength)
            {
                return value ?? string.Empty;
            }

            return value.Substring(0, maxLength) + "\n...（内容过长，已截断；原始长度 " + value.Length.ToString(CultureInfo.InvariantCulture) + " 字符）";
        }

        /// <summary>写入单份报告。失败时抛出异常，由调用方展示明确错误信息。</summary>
        public static string WriteReport(TestReport report, string projectRoot, ReportFormat format)
        {
            if (report == null)
            {
                throw new ArgumentNullException("report");
            }

            string directory = GetReportsDirectory(projectRoot);
            Directory.CreateDirectory(directory);

            string fileName = BuildFileName(report, format);
            string path = Path.Combine(directory, fileName);
            string extension = Path.GetExtension(fileName);
            string baseName = Path.GetFileNameWithoutExtension(fileName);

            // 同一份报告可能在极短时间内被重复导出，追加序号避免覆盖历史文件。
            int suffix = 2;
            while (File.Exists(path))
            {
                path = Path.Combine(directory, baseName + "_" + suffix.ToString(CultureInfo.InvariantCulture) + extension);
                suffix++;
            }

            string content = format == ReportFormat.Markdown ? BuildMarkdown(report) : BuildJson(report);
            File.WriteAllText(path, content, Utf8NoBom);
            return path;
        }

        /// <summary>同时导出 JSON 与 Markdown；两者互不影响，错误会汇总返回。</summary>
        public static ReportExportResult ExportAll(TestReport report, string projectRoot)
        {
            ReportExportResult result = new ReportExportResult();
            List<string> errors = new List<string>();

            try
            {
                result.JsonPath = WriteReport(report, projectRoot, ReportFormat.Json);
            }
            catch (Exception ex)
            {
                errors.Add("JSON 报告写入失败：" + Describe(ex));
            }

            try
            {
                result.MarkdownPath = WriteReport(report, projectRoot, ReportFormat.Markdown);
            }
            catch (Exception ex)
            {
                errors.Add("Markdown 报告写入失败：" + Describe(ex));
            }

            if (errors.Count > 0)
            {
                result.Error = string.Join("\n", errors.ToArray());
            }

            return result;
        }

        /// <summary>从磁盘读取报告。失败时返回 false 并给出错误原因，不吞异常。</summary>
        public static bool TryReadReport(string filePath, out TestReport report, out string error)
        {
            report = null;
            error = string.Empty;

            if (string.IsNullOrEmpty(filePath))
            {
                error = "报告路径为空。";
                return false;
            }

            try
            {
                string json = File.ReadAllText(filePath, Encoding.UTF8);
                report = AutoTestJson.DeserializeReport(json);
                return true;
            }
            catch (Exception ex) when (
                ex is IOException ||
                ex is UnauthorizedAccessException ||
                ex is FormatException ||
                ex is ArgumentException ||
                ex is NotSupportedException ||
                ex is System.Security.SecurityException)
            {
                error = "读取报告失败（" + filePath + "）：" + Describe(ex);
                return false;
            }
        }

        private static string Describe(Exception ex)
        {
            if (ex == null)
            {
                return "未知错误。";
            }

            Exception inner = ex.InnerException;
            if (inner != null)
            {
                return ex.GetType().Name + ": " + ex.Message + " -> " + inner.GetType().Name + ": " + inner.Message;
            }

            return ex.GetType().Name + ": " + ex.Message;
        }
    }
